#!/usr/bin/env node
// Copy the Shubhvela ids Pandit Bano links to (design.md §16.1; design-review MEDIUM 1) into content/shubhvela-ids.json:
//   muhurat   — the 14 engine activity ids of packages/engine/data/muhurat-activities.json#activities[].id
//               (URLs use these bare ids: /muhurat/marriage/2026-11/, not the 25 content ids muhurat-*)
//   festivals — the 102 slugs of packages/content/corpus/festivals/en.json[].slug
//   vrats     — the 12 VRAT_FAMILIES of packages/engine/src/calendar/vrats.ts through vratSlug() (camelCase → kebab-case,
//               replicated from web/src/data/vrats.mjs)
// plus copied = today (YYYY-MM-DD) and from = Shubhvela's `git rev-parse --short HEAD`.
//   node tools/shubhvela-ids.mjs [--shubhvela <repo path>] [--out <file>]
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DEFAULT_SHUBHVELA = resolve(ROOT, "..", "shubhvela");

/** Same rule as shubhvela/web/src/data/vrats.mjs vratSlug(): camelCase → kebab-case. */
export function vratSlug(family) {
  return family.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
}

/** Parse `export const VRAT_FAMILIES = [ 'ekadashi', … ] as const;` out of the TypeScript source. */
export function parseVratFamilies(ts) {
  const m = /export const VRAT_FAMILIES\s*=\s*\[([\s\S]*?)\]/.exec(ts);
  if (!m) throw new Error("VRAT_FAMILIES not found in vrats.ts");
  return [...m[1].matchAll(/'([A-Za-z]+)'/g)].map((x) => x[1]);
}

export function collect(shubhvela = DEFAULT_SHUBHVELA, { today = new Date() } = {}) {
  const activities = JSON.parse(readFileSync(join(shubhvela, "packages", "engine", "data", "muhurat-activities.json"), "utf8")).activities;
  const festivals = JSON.parse(readFileSync(join(shubhvela, "packages", "content", "corpus", "festivals", "en.json"), "utf8"));
  const families = parseVratFamilies(readFileSync(join(shubhvela, "packages", "engine", "src", "calendar", "vrats.ts"), "utf8"));
  let from = "unknown";
  try { from = execFileSync("git", ["--no-pager", "rev-parse", "--short", "HEAD"], { cwd: shubhvela, encoding: "utf8", env: { ...process.env, GIT_TERMINAL_PROMPT: "0" } }).trim(); } catch { /* keep "unknown" */ }
  const d = today;
  const copied = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  return {
    _note: "Generated by tools/shubhvela-ids.mjs from the Shubhvela repo — do not edit by hand (design §16.1, review MEDIUM 1). muhurat = engine activity ids used in /muhurat/{id}/{yyyy-mm}/; festivals = /festival/{slug}/{year}/; vrats = /vrat/{slug}/.",
    muhurat: activities.map((a) => a.id),
    festivals: festivals.map((f) => f.slug).sort(),
    vrats: families.map(vratSlug),
    copied,
    from,
  };
}

export function main(argv = process.argv.slice(2)) {
  let shubhvela = DEFAULT_SHUBHVELA, out = join(ROOT, "content", "shubhvela-ids.json");
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--shubhvela") shubhvela = resolve(argv[++i]);
    else if (argv[i] === "--out") out = resolve(argv[++i]);
    else throw new Error(`unknown argument ${argv[i]}`);
  }
  const ids = collect(shubhvela);
  const { _note, ...rest } = ids;
  writeFileSync(out, JSON.stringify({ _note, ...rest }, null, 2) + "\n");
  console.log(`shubhvela-ids: ${ids.muhurat.length} muhurat, ${ids.festivals.length} festivals, ${ids.vrats.length} vrats; copied ${ids.copied} from ${ids.from} → ${out}`);
}

if (process.argv[1] && resolve(fileURLToPath(import.meta.url)).toLowerCase() === resolve(process.argv[1]).toLowerCase()) main();
